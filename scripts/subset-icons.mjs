// Scans site source for Bootstrap Icon classes (bi-*), subsets the icon font
// to just those glyphs, and generates the matching CSS. Runs as part of
// `npm run build:css` so the subset always matches the templates.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import subsetFont from 'subset-font';

const ROOT = new URL('..', import.meta.url).pathname;
const SCAN_DIRS = ['_pages', '_includes', '_layouts', '_faqs', '_packages', '_posts', 'support'];
const ICON_PKG = join(ROOT, 'node_modules/bootstrap-icons/font');
const OUT_FONT = join(ROOT, 'assets/fonts/bootstrap-icons.woff2');
const OUT_CSS = join(ROOT, '_src/icons.css');

function* walk(dir) {
  for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else if (/\.(html|md)$/.test(entry.name)) yield p;
  }
}

const used = new Set();
for (const dir of SCAN_DIRS) {
  for (const file of walk(dir)) {
    const text = readFileSync(join(ROOT, file), 'utf8');
    for (const m of text.matchAll(/\bbi-([a-z0-9-]+)/g)) used.add(m[1]);
  }
}

const sourceCss = readFileSync(join(ICON_PKG, 'bootstrap-icons.css'), 'utf8');
const rules = [];
let chars = '';
for (const name of [...used].sort()) {
  const match = sourceCss.match(new RegExp(`\\.bi-${name}::before \\{ content: "\\\\([0-9a-f]+)"; \\}`));
  if (!match) {
    console.error(`ERROR: icon "bi-${name}" used in templates but not found in bootstrap-icons.`);
    process.exit(1);
  }
  chars += String.fromCodePoint(parseInt(match[1], 16));
  rules.push(`.bi-${name}::before { content: "\\${match[1]}"; }`);
}

const fontBuffer = readFileSync(join(ICON_PKG, 'fonts/bootstrap-icons.woff2'));
const subset = await subsetFont(fontBuffer, chars, { targetFormat: 'woff2' });
mkdirSync(join(ROOT, 'assets/fonts'), { recursive: true });
writeFileSync(OUT_FONT, subset);

const fullSize = statSync(join(ICON_PKG, 'fonts/bootstrap-icons.woff2')).size;
console.log(`Icons: ${used.size} glyphs, font ${(fullSize / 1024).toFixed(0)}KB -> ${(subset.length / 1024).toFixed(1)}KB`);

writeFileSync(OUT_CSS, `/* Generated by scripts/subset-icons.mjs. Do not edit by hand. */
@font-face {
  font-family: "bootstrap-icons";
  font-display: block;
  src: url("/assets/fonts/bootstrap-icons.woff2") format("woff2");
}

.bi::before,
[class^="bi-"]::before,
[class*=" bi-"]::before {
  display: inline-block;
  font-family: bootstrap-icons !important;
  font-style: normal;
  font-weight: normal !important;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  vertical-align: -.125em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules.join('\n')}
`);
console.log(`Wrote ${OUT_CSS}`);
